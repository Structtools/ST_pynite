"""Write ``docs/POLYFRAME_BUCKLING_COMPARISON.md`` from the corpus and PyNite."""

import datetime as dt
from pathlib import Path

from . import pynite_side, reference_checks
from .cases import all_cases
from .corpus import read_record

DOC = Path(__file__).resolve().parents[2] / "docs" / "POLYFRAME_BUCKLING_COMPARISON.md"
MARGIN_PCT = 5.0
GATED_VARIANT = "restraints"


def _pct(ours: float | None, theirs: float | None) -> str:
    if ours is None or theirs is None or theirs == 0:
        return "-"
    return f"{(ours - theirs) / theirs * 100:+.1f} %"


def _fmt(value: float | None, digits: int = 2) -> str:
    return "-" if value is None else f"{value:.{digits}f}"


def _status(case, key: str, ours: float | None, theirs: float | None) -> str:
    if ours is None or theirs is None:
        return "n/a"
    diff = abs(ours - theirs) / theirs * 100
    if diff <= MARGIN_PCT:
        return "ok"
    deviation = case.deviation(key)
    if deviation is not None and diff <= deviation.bound_pct:
        return f"known deviation (bound ±{deviation.bound_pct:.0f} %)"
    return "OUTSIDE"


def write_summary(path: Path = DOC, with_reference: bool = True) -> Path:
    rows_ip: list[str] = []
    rows_op: list[str] = []
    deviations: list[str] = []
    by_reason: dict[tuple, list[str]] = {}
    for case in all_cases():
        try:
            record = read_record(case.case_id)
        except FileNotFoundError:
            continue
        pf = record["polyframe"]
        ours = pynite_side.run(case)
        if case.compare_in_plane:
            theirs = pf.get("alpha_cr_ip")
            rows_ip.append(
                f"| `{case.case_id}` | {_fmt(theirs)} ({pf.get('alpha_cr_ip_source') or '-'}) "
                f"| {_fmt(ours.alpha_cr_ip, 3)} | {_pct(ours.alpha_cr_ip, theirs)} "
                f"| {_status(case, 'alpha_cr_ip', ours.alpha_cr_ip, theirs)} |"
            )
        if case.compare_out_of_plane:
            theirs = pf.get("alpha_cr_op")
            gated = ours.alpha_cr_op(GATED_VARIANT)
            rows_op.append(
                f"| `{case.case_id}` | {_fmt(theirs)} (E{pf.get('governing_element_op') or '?'}) "
                f"| {_fmt(gated, 3)} (E{ours.op_element(GATED_VARIANT)}) | {_pct(gated, theirs)} "
                f"| {_fmt(ours.alpha_cr_op_eqtorsion, 3)} | {_pct(ours.alpha_cr_op_eqtorsion, theirs)} "
                f"| {_fmt(ours.alpha_cr_op_ignore, 3)} | {_pct(ours.alpha_cr_op_ignore, theirs)} "
                f"| {_status(case, 'alpha_cr_op', gated, theirs)} |"
            )
        for deviation in case.known_deviations:
            by_reason.setdefault((deviation.key, deviation.bound_pct, deviation.reason), []).append(case.case_id)
    for (key, bound, reason), ids in by_reason.items():
        names = ", ".join(f"`{i}`" for i in ids)
        deviations.append(f"- **{names} / `{key}`** (bound ±{bound:.0f} %): {reason}")

    text = [
        "# PolyFrame buckling comparison",
        "",
        f"Generated by `python -m Testing.polyframe summary` on {dt.date.today().isoformat()} "
        "from `Testing/polyframe/corpus/` (PolyFrame 1.1.11, general method, S355, DK annex) and "
        "PyNite's `analyze_buckling`. Do not edit by hand; the modelling rules are in "
        "`Testing/polyframe/README.md` and the gate is `Testing/test_polyframe_buckling.py`.",
        "",
        f"Margin: ±{MARGIN_PCT:.0f} % on the critical load factor. PyNite runs Timoshenko members, "
        "8 elements per member, the lateral displacement restrained at every node and no other "
        "out-of-plane restraint (PolyFrame's stability supports). Columns and beams carry an "
        "unloaded 1 m stub because PolyFrame's general method refuses a straight-only structure.",
        "",
        "## In-plane critical load factor `alpha_cr`",
        "",
        "PolyFrame prints the factor on the text layer when it is above 10 and inside a formula "
        "image otherwise (`ocr`). Beams without compression have no in-plane factor.",
        "",
        "| Case | PolyFrame (source) | PyNite `plane='XY'` | Diff | Status |",
        "|---|---|---|---|---|",
        *rows_ip,
        "",
        "## Out-of-plane critical load factor `alpha_cr,op`",
        "",
        "PolyFrame's value and governing element against PyNite's first out-of-plane mode "
        "(`plane='XY', out_of_plane=True`). The gated column uses the equivalent-torsion "
        "approximation of warping on each member's **twist-restraint spacing** "
        "(`2 L` for a column standing on a twist-free base or a span of a continuous beam, `L` "
        "between frame corners and stubs). The next two columns show the same approximation on "
        "the member length, and no warping stiffness at all.",
        "",
        "The element in brackets is the one PolyFrame names under \"out-of-plane buckling mode\" and "
        "the member of PyNite's first mode. PolyFrame's label is not the mode's member (it names a "
        "column on the UDL portals while its factor equals PyNite's beam mode), so it is not gated.",
        "",
        "| Case | PolyFrame | PyNite, warping on restraint spacing | Diff | PyNite, warping on member length | Diff | PyNite, no warping | Diff | Status |",
        "|---|---|---|---|---|---|---|---|---|",
        *rows_op,
        "",
        "## Known deviations",
        "",
        "One-sided: a deviation excuses PyNite being *above* PolyFrame up to its bound, never below. "
        "A bound of 100 % is a watch, not a gate.",
        "",
        *(deviations or ["None."]),
        "",
    ]
    if with_reference:
        checks = reference_checks.run_all()
        text += [
            "## Independent reference: the governing member in a Rayleigh-Ritz Vlasov solver",
            "",
            "`Testing/polyframe/ltb_reference.py` shares no code with either tool. It expands the "
            "lateral displacement and twist of one member in polynomial series, integrates the true "
            "warping energy (no warping length, no element), and takes the member's first-order "
            "forces from a PyNite static solve (which agree with PolyFrame's to 0.2 %). End "
            "conditions: lateral displacement held at both ends; twist held where another member "
            "meets the end at an angle (frame corner, stub), free at a bare support; warping free. "
            "Validated against closed forms in `Testing/test_ltb_reference.py` (uniform moment, "
            "Timoshenko & Gere UDL and point-load coefficients, three-factor load-height formula, "
            "torsional buckling with three end conditions, beam-column interaction).",
            "",
            "Read the table with two caveats. (1) Isolating a member assumes the rest of the frame "
            "acts as rigid forks at its ends; the stiffness ratios support that here (see "
            "`reference_checks.py`). (2) A member with a **moment at a twist-free end** (a column on "
            "a base that holds no twist but carries a fixing moment) is a configuration where the "
            "second-order work of that end moment depends on how the moment is modelled, and the "
            "solver's answer is not an adjudication; such members are marked `no/yes` with a "
            "non-zero base moment. For rafters between frame corners and for columns with zero "
            "base moment the solver is a clean third reference.",
            "",
            reference_checks.format_table(checks),
            "",
        ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(text), encoding="utf-8")
    return path
